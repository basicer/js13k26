// Entity offsets are Float32Array indices, derived from WGSL storage layout.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const roundUp = (alignment, size) => Math.ceil(size / alignment) * alignment;

function splitMembers(text) {
	let depth = 0, start = 0;
	const members = [];
	for (let i = 0; i < text.length; i++) {
		if (text[i] === "<") depth++;
		if (text[i] === ">") depth--;
		if (text[i] === "," && depth === 0) {
			members.push(text.slice(start, i).trim());
			start = i + 1;
		}
	}
	members.push(text.slice(start).trim());
	return members.filter(Boolean);
}

function layout(type) {
	if (/^(f32|i32|u32)$/.test(type)) return { alignment: 4, size: 4 };
	const vector = /^vec([234])<(f32|i32|u32)>$/.exec(type);
	if (vector) {
		const components = Number(vector[1]);
		return { alignment: components === 2 ? 8 : 16, size: components * 4, components };
	}
	const array = /^array<(.+)>$/.exec(type);
	if (array) {
		const args = splitMembers(array[1]);
		const [element, count] = args;
		if (args.length !== 2 || !/^[1-9]\d*$/.test(count)) throw Error(`Expected a fixed array length: ${type}`);
		const { alignment, size } = layout(element);
		return { alignment, size: roundUp(alignment, size) * Number(count) };
	}
	throw Error(`Unsupported Entity field type: ${type}`);
}

export function generateEntityConstants(source) {
	const clean = source.replace(/\/\*[\s\S]*?\*\/|\/\/[^\r\n]*/g, "");
	const body = /\bstruct\s+Entity\s*\{([^}]+)\}/.exec(clean)?.[1];
	if (!body) throw Error("Entity struct not found");
	const lines = [
		"// Generated by scripts/generate-entity-constants.mjs from shaders/common.wgsl.",
		"// Float32Array indices (not byte offsets). Do not edit by hand.",
	];
	let offset = 0, structAlignment = 1;
	const names = new Set();
	const emit = (name, value) => {
		if (names.has(name)) throw Error(`Duplicate constant: ${name}`);
		names.add(name);
		lines.push(`export const ${name} = ${value};`);
	};
	for (const member of splitMembers(body)) {
		const match = /^([A-Za-z_]\w*)\s*:\s*(.+)$/.exec(member);
		if (!match) throw Error(`Unsupported Entity member: ${member}`);
		const name = match[1].replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
		const { alignment, size, components } = layout(match[2].replace(/\s/g, ""));
		offset = roundUp(alignment, offset);
		structAlignment = Math.max(structAlignment, alignment);
		emit(name, offset / 4);
		for (let axis = 0; axis < (components || 0); axis++) emit(`${name}_${"XYZW"[axis]}`, offset / 4 + axis);
		offset += size;
	}
	emit("STRIDE", roundUp(structAlignment, offset) / 4);
	return lines.join("\n") + "\n";
}

export function writeEntityConstants() {
	const source = readFileSync(new URL("../shaders/common.wgsl", import.meta.url), "utf8");
	const output = new URL("../src/entities-const.js", import.meta.url);
	const generated = generateEntityConstants(source);
	let current;
	try { current = readFileSync(output, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
	if (current?.replaceAll("\r\n", "\n") !== generated) writeFileSync(output, generated);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) writeEntityConstants();
